"""Ten example Decode cards, as a table (Checkpoint 2). All inputs are made up (synthetic); none comes from a real worker.

    python eval/decode_examples.py            # print
    python eval/decode_examples.py --write    # also write eval/DECODE_EXAMPLES.md
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "engine"))

from steve_engine.decode import decode  # noqa: E402

# (heard or typed, accent hint, path). Ten cases that show what the decoder does and, as importantly, what it leaves alone.
CASES = [
    ("yalla habibi come to the barking gate tree", "ar", "typed"),
    ("yalla habibi come to the barking gate three", "ar", "voice"),
    ("the barking dog is at the gate", "ar", "voice"),
    ("bring the bebsi from the fridge", "ar", "typed"),
    ("come to the barking or the building?", "ar", "voice"),
    ("don't come to the barking now, khalas", "ar", "voice"),
    ("wait one minute, inshallah I send the money tomorrow", None, "typed"),
    ("wery good, come at fife", "hi", "typed"),
    ("come to the gate free", None, "voice"),
    ("pay fifty dirhams tomorrow, kindly revert", "ml", "typed"),
]


def cell(x) -> str:
    return str(x).replace("|", "/") if x not in (None, "", []) else "-"


def row(text: str, hint: str | None, path: str) -> str:
    c = decode(text, hint, path)
    a = c.actions
    acts = ", ".join(f"{k}: {v.value}" for k, v in (("where", a.where), ("when", a.when), ("what", a.what), ("how much", a.how_much)) if v) or "-"
    changes = "; ".join(f"{x.heard} -> {x.meant}" for x in c.changes) or "-"
    phrases = ", ".join(p.phrase for p in c.phrases) or "-"
    asks = " / ".join(q.question for q in c.clarify) or "-"
    return f"| `{text}` | {hint or '-'} / {path} | {cell(c.plain_english)} | {changes} | {phrases} | {acts} | {cell(asks)} |"


def build() -> str:
    head = ["| Heard or typed (made up) | Accent / path | Plain English | Changes | Phrases explained | Actions | Question asked |", "|---|---|---|---|---|---|---|"]
    return "\n".join(head + [row(*c) for c in CASES])


if __name__ == "__main__":
    table = build()
    print(table)
    if "--write" in sys.argv:
        (ROOT / "eval" / "DECODE_EXAMPLES.md").write_text(
            "# Ten example Decode cards\n\nGenerated by `python eval/decode_examples.py --write`. Every input is made up; every glossary meaning, accent rule and domain word is "
            "`verified: false` until a native speaker checks it (D36, D40).\n\n" + table + "\n",
            encoding="utf-8",
        )

"""Fill the evaluation table in README.md from eval/results/latest.json (between the EVAL markers)."""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
LATEST = ROOT / "eval" / "results" / "latest.json"
START, END = "<!-- EVAL:START -->", "<!-- EVAL:END -->"


def pct(x: float) -> str:
    return f"{x * 100:.1f}%"


def row(name: str, b: dict | None) -> str:
    if not b:
        return f"| {name} | n/a | n/a | n/a |"
    return f"| {name} | {b['n']} | {pct(b['accuracy'])} | {b['false_understood']}/{b['false_understood_denominator']} ({pct(b['false_understood_rate'])}) |"


def build(d: dict) -> str:
    e, b = d["engine"], d["baseline"]
    lines = [
        (
            f"_Generated by `eval/update_readme.py` from `eval/results/latest.json` on {d['generated_at']}. "
            f"{d['n_fact_checks']} labelled fact checks across {d['n_replies']} replies "
            f"({d['n_handwritten']} hand-written, {d['n_synthetic']} synthetic)._"
        ),
        "",
        "| System / slice | Fact checks | Accuracy | False “understood” |",
        "|---|---:|---:|---:|",
        row("**Our engine · all**", e["overall"]),
    ]
    for k, v in e["by_source"].items():
        lines.append(row(f"Our engine · {k}", v))
    for k, v in e["by_language"].items():
        lines.append(row(f"Our engine · {k}", v))
    if b.get("available"):
        lines.append(row(f"**Gemini baseline** (same replies, {b['consistency']['runs']} runs, majority vote)", b["overall"]))
        lines.append(row("Our engine on the baseline's exact subset", b.get("engine_on_same_subset")))
        lines += ["", f"Baseline self-consistency across runs: **{pct(b['consistency']['mean_agreement'])}** (our engine: 100%, deterministic). {b.get('note', '')}"]
    else:
        lines += ["", "**LLM baseline: not run** (no Gemini key when this was generated), so no comparison is claimed. Set `GEMINI_API_KEY` and run `make eval`."]
    lines += ["", "**Caveats** (please read):"] + [f"- {c}" for c in d["caveats"]]
    return "\n".join(lines)


def main() -> None:
    if not LATEST.exists():
        sys.exit("eval/results/latest.json not found. Run: make eval")
    block = build(json.loads(LATEST.read_text(encoding="utf-8")))
    text = README.read_text(encoding="utf-8")
    if START not in text or END not in text:
        sys.exit(f"README.md is missing the {START} / {END} markers")
    new = re.sub(re.escape(START) + r".*?" + re.escape(END), f"{START}\n{block}\n{END}", text, flags=re.DOTALL)
    README.write_text(new, encoding="utf-8")
    print("README.md evaluation table updated")


if __name__ == "__main__":
    main()

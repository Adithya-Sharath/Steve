"""Build `eval/results/decode_metrics.json`, the labelled Decode numbers that `GET /decode/eval` serves to the Evaluation page (D50).

    python eval/decode_metrics_export.py

Nothing is typed in by hand except `decode_reference_numbers.json` (numbers recorded from runs that need audio we do not commit: L2-ARCTIC speech-to-text results, D40 / D42 / D43).
Everything else is read from files this repo produced: the first-run reports of the v1 and v2 sets (parsed from their tables), a live scoring of the synthetic voice set, and
the Gemini baseline summary when it exists. Every section carries the label that must travel with its numbers (synthetic, author-written, tuned on it ...).
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "engine"))
sys.path.insert(0, str(ROOT / "eval"))
RES = ROOT / "eval" / "results"


def table_rows(md: str, first_cell: str) -> list[list[str]]:
    out = []
    for line in md.splitlines():
        if line.startswith("|") and line.split("|")[1].strip() == first_cell:
            out.append([c.strip() for c in line.strip().strip("|").split("|")])
    return out


def short(cell: str) -> str:
    """'94.0% (63/67; 95% 86-98%)' -> '94.0% (63/67)'."""
    return re.sub(r";\s*95%[^)]*\)", ")", cell)


def first_run(name: str) -> dict:
    md = (RES / name).read_text(encoding="utf-8")
    fa = table_rows(md, "All correct sentences")[0]
    ear = {r[0]: r for r in (table_rows(md, "In-pack") + table_rows(md, "Out-of-pack") + table_rows(md, "All"))}
    ext: dict[str, list[list[str]]] = {}
    for view in ("Typed correctly", "Voice transcript, correct"):
        ext[view] = [r for r in table_rows(md, view) if len(r) == 8]
    return {"fa": fa, "ear": ear, "ext": ext}


def sections() -> tuple[list[dict], list[str]]:
    used = []
    out: list[dict] = []
    v2, v1 = first_run("decode_eval_v2_first_run.md"), first_run("decode_eval_v1_first_run.md")
    used += ["eval/results/decode_eval_v2_first_run.md", "eval/results/decode_eval_v1_first_run.md"]
    out.append({
        "id": "false_alarm", "title": "False alarms (headline)",
        "label": "synthetic, author-written; v2 was written after the engine was tuned and scored once, v1 was frozen before its first run",
        "note": "A correctly written sentence for which the card shows any change or any clarifying question. Lower is better.",
        "rows": [
            {"metric": "v2 first run: any change or question", "value": short(v2["fa"][2]), "detail": f"silent rewrites: {short(v2['fa'][3])}; questions only: {short(v2['fa'][4])}"},
            {"metric": "v1 first run: any change or question", "value": short(v1["fa"][2]), "detail": f"silent rewrites: {short(v1['fa'][3])}"},
        ],
    })
    rows = []
    for key, label in (("In-pack", "respellings the accent packs cover"), ("Out-of-pack", "respellings the packs do NOT model"), ("All", "both together (mix unknown in real life)")):
        r = v2["ear"][key]
        rows.append({"metric": f"v2 first run, {label}: exact / asked / left as typed / wrong rewrite", "value": short(r[2]),
                     "detail": f"asked {short(r[3])}; left as typed {short(r[5])}; wrong rewrite {short(r[6])}"})
    out.append({"id": "typed_ear", "title": "Typed-text decode accuracy (headline)", "label": "synthetic; the respellings are generated by letter rules, real people vary far more",
                "note": "Sentences typed by ear. Exact = the intended sentence is recovered. Out-of-pack respellings are not decoded: that is the honest limit.", "rows": rows})
    rows = []
    for view, label in (("Typed correctly", "typed correctly"), ("Voice transcript, correct", "voice transcript, correct")):
        for r in v2["ext"][view]:
            rows.append({"metric": f"v2 first run, {label}: {r[1]}", "value": short(r[3]), "detail": f"gold present {r[2]}; partial {r[4]}; empty {r[5]}; wrong {short(r[6])}; spurious fills {short(r[7])}"})
    out.append({"id": "extraction", "title": "Where / when / what / how much extraction (headline)", "label": "synthetic, author-written gold labels; one author",
                "note": "Correct = equals the gold value after dropping articles and prepositions. Partial = right but incomplete. Wrong values are the dangerous kind.", "rows": rows})

    from decode_safety_eval import evaluate_voice, load

    res = evaluate_voice(load(ROOT / "data" / "decode" / "voice_synthetic.csv"))
    r, c = res["risky"]["all"], res["clean"]["all"]
    caught = r["caught_rewrite"] + r["caught_clarify"]
    ref = json.loads((RES / "decode_reference_numbers.json").read_text(encoding="utf-8"))
    used.append("eval/results/decode_reference_numbers.json")
    out.append({
        "id": "voice_net", "title": "Voice safety net: catch rate", "label": "synthetic, author-written, tuned on it (first row); held-out L2-ARCTIC (second row)",
        "note": "The net only looks at critical words (a place, time, amount or number). The held-out errors are literary words outside those slots, so 0 caught says the net is not a general speech-to-text fixer, not how it would do on workplace instructions.",
        "rows": [
            {"metric": "synthetic, author-written, tuned on it: risky words caught", "value": f"{100 * caught / r['n']:.1f}% ({caught}/{r['n']})", "detail": f"{r['caught_rewrite']} rewritten, {r['caught_clarify']} asked, {r['wrong_rewrite']} wrong rewrites; false alarm {c['any']} of {c['n']} clean sentences"},
            *ref["voice_net_heldout"],
        ],
    })
    out.append({"id": "stt", "title": "Speech-to-text on accented read speech (Sarvam transcribe)", "label": ref["stt_label"], "note": ref["stt_note"], "rows": ref["stt_rows"]})
    base = RES / "decode_baseline_v2.json"
    if base.exists():
        b = json.loads(base.read_text(encoding="utf-8"))
        used.append("eval/results/decode_baseline_v2.json")
        rows = []
        e, g = b["engine"], b["gemini"]

        def rt(x, n):
            return f"{100 * x / n:.1f}% ({x}/{n})" if n else "n/a"

        rows.append({"metric": "false rewrite on correct sentences (lower is better)", "value": f"engine {rt(e['clean']['false_rewrite'], e['clean']['n'])} | Gemini {rt(g['clean']['false_rewrite'], g['clean']['n'])}", "detail": None})
        for key, label in (("true", "in-pack"), ("false", "out-of-pack")):
            ce, cg = e["ear"][key], g["ear"][key]
            rows.append({"metric": f"typed by ear, {label}: intended sentence recovered", "value": f"engine {rt(ce.get('exact', 0), ce['n'])} | Gemini {rt(cg.get('exact', 0), cg['n'])}", "detail": f"wrong rewrites: engine {ce.get('wrong_rewrite', 0)}, Gemini {cg.get('wrong_rewrite', 0)}"})
        for s in ("where", "when", "what", "how_much"):
            ce, cg = e["slots"][s], g["slots"][s]
            ne = sum(ce.get(k, 0) for k in ("correct", "partial", "empty", "wrong"))
            ng = sum(cg.get(k, 0) for k in ("correct", "partial", "empty", "wrong"))
            rows.append({"metric": f"{s}: correct", "value": f"engine {rt(ce.get('correct', 0), ne)} | Gemini {rt(cg.get('correct', 0), ng)}", "detail": f"wrong values: engine {ce.get('wrong', 0)}, Gemini {cg.get('wrong', 0)}"})
        rows.append({"metric": "negation lost (lower is better)", "value": f"engine {e['neg'].get('lost', 0)}/{e['neg']['n']} | Gemini {g['neg'].get('lost', 0)}/{g['neg']['n']}", "detail": None})
        out.append({"id": "baseline", "title": f"Gemini baseline on the v2 set ({b["model"]}, at most {b["calls_made"]} calls)",
                    "label": "synthetic, author-written; the engine column is contaminated on v2 (small fixes after its first run); Gemini got the same accent hint", "note": "Where Gemini wins is in the report file eval/results/decode_baseline_v2.md.", "rows": rows})
    out.append({"id": "missing", "title": "What has not been measured", "label": "read this first",
                "note": "There are no real workers, no real voice notes and no real typed messages in any number on this page. Every accent rule, glossary entry and word list is unreviewed (verified: false). "
                        "Translations are checked for numbers only, nobody has checked that a negation survives.",
                "rows": [{"metric": "real-world validation", "value": "none", "detail": "public read speech and synthetic, author-written data only"}]})
    return out, used


def main() -> None:
    secs, used = sections()
    doc = {"available": True, "generated_from": used, "caveats": [
        "Every number is a development number from public read speech or synthetic, author-written data (one author wrote sentences, gold labels and respellings).",
        "Frozen sets were committed before their first scoring run; sets used to find fixes are labelled contaminated.",
    ], "sections": secs}
    (RES / "decode_metrics.json").write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print("wrote eval/results/decode_metrics.json with", len(secs), "sections")


if __name__ == "__main__":
    main()
